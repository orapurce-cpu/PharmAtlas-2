// Helper database index
export const ALL_DRUGS_FLAT: DrugItem[] = MASTER_DRUG_GROUPS.flatMap(g => g.drugs);

export function searchDrugsLocal(query: string): DrugItem[] {
  if (!query || !query.trim()) return ALL_DRUGS_FLAT.slice(0, 10);
  const q = query.toLowerCase().trim();
  return ALL_DRUGS_FLAT.filter(d => {
    const innMatch = d.inn.toLowerCase().includes(q) || (d.inn_lat && d.inn_lat.toLowerCase().includes(q));
    const tradeMatch = d.trade_names.some(t => t.toLowerCase().includes(q));
    const groupMatch = d.group_name.toLowerCase().includes(q);
    return innMatch || tradeMatch || groupMatch;
  });
}

